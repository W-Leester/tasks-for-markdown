// Writes THIRD_PARTY_NOTICES.md: every third-party package that esbuild bundles into the extension,
// the webviews and the CLI (dist/tasksmd.cjs, also the npm package), with its license text.
// `node scripts/third-party-notices.mjs --check` exits 1 when the file is out of date (tests use it).
import * as esbuild from 'esbuild';
import esbuildSvelte from 'esbuild-svelte';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUT = 'THIRD_PARTY_NOTICES.md';
const apps = readdirSync('src/webviews', { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(`src/webviews/${d.name}/main.ts`)).map((d) => d.name);
const common = { bundle: true, write: false, metafile: true, logLevel: 'silent' };
const builds = {
  extension: { ...common, entryPoints: ['src/extension.ts'], platform: 'node', format: 'cjs', external: ['vscode'], outfile: 'x.js' },
  webviews: { ...common, entryPoints: Object.fromEntries(apps.map((a) => [a, `src/webviews/${a}/main.ts`])), outdir: 'x', format: 'iife', platform: 'browser', conditions: ['svelte', 'browser'], plugins: [esbuildSvelte({ compilerOptions: { css: 'external' }, filterWarnings: () => false })] },
  cli: { ...common, entryPoints: ['packages/cli/src/main.ts'], platform: 'node', format: 'cjs', outfile: 'x.cjs', define: { __TASKSMD_VERSION__: '"x"' } },
};

/** package root dir -> where it is bundled */
const found = new Map();
for (const [where, options] of Object.entries(builds)) {
  const { metafile } = await esbuild.build(options);
  for (const input of Object.keys(metafile.inputs)) {
    const m = /^(.*?node_modules\/(?:\.pnpm\/[^/]+\/node_modules\/)?(?:@[^/]+\/)?[^/]+)\//.exec(input);
    if (!m) continue;
    const root = m[1];
    if (!found.has(root)) found.set(root, new Set());
    found.get(root).add(where);
  }
}

const LICENSE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md', 'LICENCE', 'LICENCE.md', 'LICENSE-MIT', 'LICENSE-MIT.txt'];
const packages = [...found.entries()].map(([root, where]) => {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const file = LICENSE_FILES.map((f) => join(root, f)).find((f) => existsSync(f));
  if (!file) throw new Error(`No license file for ${pkg.name} (${root})`);
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? '';
  return { name: pkg.name, version: pkg.version, license: pkg.license ?? '(see text)', repo: repo.replace(/^git\+/, '').replace(/\.git$/, '').replace(/^github:/, '').replace(/^([\w.-]+\/[\w.-]+)$/, 'https://github.com/$1').replace(/^git:\/\//, 'https://'), where: [...where].sort(), text: readFileSync(file, 'utf8').trim() };
});
// One entry per package name (the same package can be resolved twice); keep the highest version.
const byName = new Map();
for (const p of packages.sort((a, b) => a.name.localeCompare(b.name) || b.version.localeCompare(a.version, undefined, { numeric: true }))) {
  if (byName.has(p.name)) byName.get(p.name).where = [...new Set([...byName.get(p.name).where, ...p.where])].sort();
  else byName.set(p.name, p);
}
const list = [...byName.values()];

const out = [
  '# Third-party notices',
  '',
  'Tasks for Markdown bundles the following open-source packages into its files (the extension, its webviews and the `tasksmd` command / MCP server).',
  'Each package keeps its own license; the full texts follow. Generated by `scripts/third-party-notices.mjs` — do not edit by hand.',
  '',
  'Tasks for Markdown에 함께 들어가는 오픈소스 패키지와 라이선스 전문입니다(자동 생성).',
  '',
  '| Package | Version | License | Bundled in |',
  '|---|---|---|---|',
  ...list.map((p) => `| ${p.repo ? `[${p.name}](${p.repo})` : p.name} | ${p.version} | ${p.license} | ${p.where.join(', ')} |`),
  '',
  ...list.flatMap((p) => [`## ${p.name} ${p.version}`, '', '```text', p.text, '```', '']),
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error(`${OUT} is out of date — run: node scripts/third-party-notices.mjs`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${list.length} packages)`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT} (${list.length} packages)`);
}
